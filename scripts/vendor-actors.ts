// Copies engine/, shared/types.ts, shared/protocol.ts and seed/*.json into actors/src/vendor/.
// `terse deploy` uploads only actors/, so everything the actors import must live inside it.
// Run via `bun run actors:dev` / `bun run actors:deploy` (both call this first). Don't edit vendor/.
import { mkdirSync, readdirSync, rmSync, copyFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const out = join(root, "actors/src/vendor");
rmSync(out, { recursive: true, force: true });
const copy = (from: string, to: string) => { mkdirSync(join(out, to, ".."), { recursive: true }); copyFileSync(join(root, from), join(out, to)); };

for (const f of readdirSync(join(root, "engine"))) if (f.endsWith(".ts") && !f.endsWith(".test.ts")) copy(`engine/${f}`, `engine/${f}`);
for (const f of ["types.ts", "protocol.ts"]) copy(`shared/${f}`, `shared/${f}`);
for (const f of ["battery.json", "actuators.json", "software.json", "controls.json", "robotics.json"]) copy(`seed/${f}`, `seed/${f}`);
writeFileSync(join(out, "README.md"), "Generated by scripts/vendor-actors.ts. Edit the originals, not these copies.\n");
console.log(`vendored engine, shared contract and seeds into ${out}`);
